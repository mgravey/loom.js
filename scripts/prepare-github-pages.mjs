import { cp, lstat, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const source = join(root, 'packages', 'example-codex-experimental');
const output = join(root, 'site-preview');
const defaultOrigin = 'https://mgravey.com';
const defaultBasePath = '/loom.js';
const defaultChromeExtensionId = 'gdcebopdllcifgleoefgbobdopiaholg';
const supportEmail = process.env.LOOM_SUPPORT_EMAIL?.trim() || 'sideproject@mgravey.com';
const securityEmail = process.env.LOOM_SECURITY_EMAIL?.trim() || supportEmail;

function publicOrigin() {
  const raw = process.env.LOOM_SITE_ORIGIN?.trim() || defaultOrigin;
  const value = new URL(raw);
  if (
    value.protocol !== 'https:' ||
    value.origin !== raw ||
    value.username !== '' ||
    value.password !== '' ||
    value.port !== ''
  ) {
    throw new Error('LOOM_SITE_ORIGIN must be an exact public HTTPS origin on the standard port.');
  }
  return value.origin;
}

function publicBasePath() {
  const raw = process.env.LOOM_SITE_BASE_PATH?.trim() || defaultBasePath;
  const value = `/${raw.replace(/^\/+|\/+$/gu, '')}`;
  if (value === '/' || !/^\/[a-zA-Z0-9._~/-]+$/u.test(value)) {
    throw new Error('LOOM_SITE_BASE_PATH must be a non-root URL path such as /loom.js.');
  }
  return value;
}

function optionalExtensionId() {
  const value = process.env.LOOM_CHROME_EXTENSION_ID?.trim() || defaultChromeExtensionId;
  if (value !== '' && !/^[a-p]{32}$/u.test(value)) {
    throw new Error('LOOM_CHROME_EXTENSION_ID must be a 32-character Chrome extension ID.');
  }
  return value;
}

function optionalStoreUrl() {
  const raw = process.env.LOOM_CHROME_WEB_STORE_URL?.trim() || '';
  if (raw === '') return '';
  const value = new URL(raw);
  if (value.protocol !== 'https:' || value.hostname !== 'chromewebstore.google.com') {
    throw new Error('LOOM_CHROME_WEB_STORE_URL must be an HTTPS Chrome Web Store URL.');
  }
  return value.href;
}

function assertEmail(label, value) {
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/u.test(value) || value.endsWith('.invalid')) {
    throw new Error(`${label} must be a deliverable email address.`);
  }
}

const origin = publicOrigin();
const basePath = publicBasePath();
const siteUrl = `${origin}${basePath}/`;
const legalName = process.env.LOOM_LEGAL_NAME?.trim() || 'Mathieu Gravey';
assertEmail('LOOM_SUPPORT_EMAIL', supportEmail);
assertEmail('LOOM_SECURITY_EMAIL', securityEmail);

const files = [
  'THIRD_PARTY_NOTICES.txt',
  'docs.html',
  'index.html',
  'install.html',
  'legal.html',
  'privacy.html',
  'site.css',
  'site.js',
  'support.html',
  'terms.html',
  'workbench.html',
];

await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
for (const file of files) await cp(join(source, file), join(output, file));
await cp(join(source, 'assets'), join(output, 'assets'), { recursive: true });
await mkdir(join(output, 'dist'), { recursive: true });
for (const file of ['brand-animation.js', 'main.js']) {
  await cp(join(source, 'dist', file), join(output, 'dist', file));
}

const deploymentConfig = `// Generated by scripts/prepare-github-pages.mjs. Do not place secrets here.
globalThis.LOOM_DEPLOYMENT_CONFIG = Object.freeze(${JSON.stringify(
  {
    environment: 'production',
    chromeExtensionId: optionalExtensionId(),
    chromeWebStoreUrl: optionalStoreUrl(),
    siteOrigin: origin,
    siteBasePath: basePath,
    siteUrl,
    legalName,
    supportEmail,
    securityEmail,
  },
  null,
  2,
)});
`;
await writeFile(join(output, 'deployment-config.js'), deploymentConfig);
await writeFile(join(output, '.nojekyll'), '');
await writeFile(
  join(output, 'deployment-manifest.json'),
  `${JSON.stringify(
    {
      generatedAt: new Date().toISOString(),
      siteUrl,
      origin,
      basePath,
      extensionConfigured: optionalExtensionId() !== '',
      chromeWebStoreUrlConfigured: optionalStoreUrl() !== '',
      publisherConfigured: !legalName.startsWith('REPLACE_'),
      supportEmail,
      files: [
        ...files,
        'assets/',
        'dist/brand-animation.js',
        'dist/main.js',
        'deployment-config.js',
        'deployment-manifest.json',
        '.nojekyll',
      ],
    },
    null,
    2,
  )}\n`,
);

for (const directory of ['assets', 'dist']) {
  const details = await lstat(join(output, directory));
  if (details.isSymbolicLink())
    throw new Error(`Pages artifact must not contain ${directory} as a symlink.`);
}

for (const file of files.filter((value) => value.endsWith('.html'))) {
  const html = await readFile(join(output, file), 'utf8');
  for (const match of html.matchAll(/(?:href|src)=["']\.\/([^"'#?]+)(?:[?#][^"']*)?["']/gu)) {
    const target = join(output, match[1]);
    try {
      await lstat(target);
    } catch (error) {
      throw new Error(`${file} references missing Pages asset ${match[1]}.`, { cause: error });
    }
  }
}

console.log(`GitHub Pages artifact: ${output}`);
console.log(`Expected public URL: ${siteUrl}`);
